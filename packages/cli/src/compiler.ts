import type { BrickIR, RouteIR } from "@brickkit/core";

/**
 * A route's handler factory for `brick build`: it binds the runtime pipeline, so no framework logic is emitted.
 *
 * @deprecated `brick build` no longer emits handler factories; built servers bind routes at startup.
 */
export function emitHandlerFactory(_route: RouteIR): string {
  return "function bindAction(binding, runtime) { return runtime.bindRoute(binding); }";
}

/** The `routes.js` module of a build: the compiled IR the built server checks its app against. */
export function emitCompiledApplication(
  ir: BrickIR,
  /** @deprecated Unused: the module no longer imports the runtime. */
  _runtimeImport?: string,
): string {
  return `// Generated by Brick compiler v1. Rebuild after changing application definitions.\nexport const ir = JSON.parse(${JSON.stringify(JSON.stringify(ir))});\n`;
}
